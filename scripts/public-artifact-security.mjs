import { randomBytes } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { isDeepStrictEqual } from 'node:util';
import { Unzip, UnzipInflate } from 'fflate';
import { normalizeNetworkConfig } from '../src/network-config.mjs';

export const serverCredentialNames = Object.freeze([
  'CLOUDFLARE_API_TOKEN', 'TURNSTILE_SECRET_KEY', 'STAGING_TEST_SECRET',
  'NETWORK_STAGING_TEST_SECRET', 'SESSION_SIGNING_KEY',
]);

export function createBuildCanaries() {
  return Object.fromEntries(serverCredentialNames.map(name => [name, `artifact-canary:${randomBytes(36).toString('base64')}+/="`]));
}

export function canaryRepresentations(canaries) {
  if (!canaries || Object.keys(canaries).length !== serverCredentialNames.length
    || serverCredentialNames.some(name => typeof canaries[name] !== 'string' || canaries[name].length < 48)) {
    throw new Error('The artifact check requires a fresh complete set of harmless build canaries.');
  }
  return [...new Set(Object.values(canaries).flatMap(value => [
    value, JSON.stringify(value).slice(1, -1), encodeURIComponent(value),
    Buffer.from(value).toString('base64'), Buffer.from(value).toString('base64url'),
    Buffer.from(value).toString('hex'), Buffer.from(value).toString('hex').toUpperCase(),
    [...value].map(char => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`).join(''),
  ]))];
}

function privatePath(relative) {
  return /(?:^|\/)services\/network-worker(?:\/|$)/.test(relative)
    || /(?:^|\/)(?:wrangler\.(?:jsonc?|toml)|\.dev\.vars(?:\..+)?|\.env(?:\..+)?|network\.staging\.json|public-artifact-canaries\.json)$/.test(relative)
    || /^(?:\.git|\.github)(?:\/|$)/.test(relative);
}

function byteInspector(patterns, label) {
  const overlap = Math.max(...patterns.map(pattern => pattern.length)) - 1;
  let previous = Buffer.alloc(0);
  return chunk => {
    const bytes = Buffer.concat([previous, Buffer.from(chunk)]);
    if (patterns.some(pattern => bytes.includes(pattern))) {
      // Never include the detected credential or surrounding content in errors.
      throw new Error(`Server credential canary leaked into public artifact: ${label}`);
    }
    previous = Buffer.from(bytes.subarray(Math.max(0, bytes.length - overlap)));
  };
}

async function inspectGeneratedZip(filename, relative, patterns) {
  let failure, entries = 0, expandedBytes = 0;
  const unzip = new Unzip(file => {
    try { byteInspector(patterns, 'snapshot entry pathname')(Buffer.from(file.name)); }
    catch (error) { failure = error; return; }
    if (++entries > 100000 || privatePath(file.name)) {
      failure = new Error('Private or excessive entries in generated snapshot.');
      return;
    }
    const inspect = byteInspector(patterns, 'generated snapshot entry');
    file.ondata = (error, bytes) => {
      if (failure) return;
      if (error) { failure = new Error('Cannot inspect generated snapshot.'); return; }
      expandedBytes += bytes.length;
      if (expandedBytes > 1024 * 1024 * 1024) { failure = new Error('Generated snapshot exceeds the inspection limit.'); return; }
      try { inspect(bytes); } catch (error) { failure = error; }
    };
    file.start();
  });
  unzip.register(UnzipInflate);
  for await (const bytes of createReadStream(filename)) {
    unzip.push(bytes);
    if (failure) throw failure;
  }
  unzip.push(new Uint8Array(), true);
  if (failure) throw failure;
  return { entries, expandedBytes };
}

/** Scan real generated bytes, including binary outputs and compressed site snapshots. */
export async function verifyPublicArtifact({ directory, canaries, environment = 'production' }) {
  if (!['production', 'staging'].includes(environment)) throw new Error('Invalid artifact environment.');
  const strings = canaryRepresentations(canaries);
  const patterns = strings.flatMap(value => [Buffer.from(value), Buffer.from(value, 'utf16le')]);
  const result = { environment, files: 0, bytes: 0, snapshots: 0, snapshotEntries: 0, snapshotExpandedBytes: 0 };
  async function visit(prefix = '') {
    for (const entry of await readdir(path.join(directory, prefix), { withFileTypes: true })) {
      const relative = path.posix.join(prefix, entry.name);
      byteInspector(patterns, 'public artifact pathname')(Buffer.from(relative));
      if (privatePath(relative)) throw new Error('Server-only file in public artifact.');
      if (entry.isDirectory()) { await visit(relative); continue; }
      if (!entry.isFile()) throw new Error('Non-regular public artifact.');
      const filename = path.join(directory, relative);
      const inspect = byteInspector(patterns, 'public artifact contents');
      for await (const bytes of createReadStream(filename)) { inspect(bytes); result.bytes += bytes.length; }
      result.files++;
      // Downloaded Joomla/extension archives were hash-verified by the build.
      // Only our generated snapshots need decompression for this canary check.
      if (/^assets\/snapshots\/[^/]+\.zip$/.test(relative)) {
        const snapshot = await inspectGeneratedZip(filename, relative, patterns);
        result.snapshots++; result.snapshotEntries += snapshot.entries; result.snapshotExpandedBytes += snapshot.expandedBytes;
      }
    }
  }
  await visit();
  const manifest = JSON.parse(await readFile(path.join(directory, 'assets/manifest.json'), 'utf8'));
  const config = JSON.parse(await readFile(path.join(directory, 'config/network.json'), 'utf8'));
  const normalized = normalizeNetworkConfig(config);
  if (!isDeepStrictEqual(config, normalized) || !isDeepStrictEqual(manifest.network, normalized)) {
    throw new Error('Public network manifest/config must contain only the complete normalized public schema.');
  }
  if (manifest.schemaVersion !== 1 || !/^[a-f0-9]{40}$/.test(manifest.sourceCommit || '')
    || manifest.deployment?.environment !== environment) throw new Error('Public artifact deployment identity is invalid.');
  if (environment === 'production' && normalized.enabled
    && (!normalized.turnstileSiteKey || /^[123]x0{20}[A-Z]{2}$/.test(normalized.turnstileSiteKey))) {
    throw new Error('Production artifacts cannot enable a Turnstile test key.');
  }
  return { ...result, sourceCommit: manifest.sourceCommit, serverCredentialChecks: [...serverCredentialNames] };
}
